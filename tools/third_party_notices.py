#!/usr/bin/env python3
"""Regenerates THIRD_PARTY_NOTICES.md from the license files vcpkg installs for the components
that are linked into cadpreview, plus the embedded font's license.

    python tools/third_party_notices.py build/win-release/vcpkg_installed/x64-windows-static-md

Run it after adding or upgrading a shipped dependency, and review the diff.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent


@dataclass(frozen=True)
class Component:
    port: str
    name: str
    license: str
    purpose: str


SHIPPED = (
    Component("libpng", "libpng", "libpng-2.0", "PNG encoding and decoding"),
    Component("zlib", "zlib", "Zlib", "compression for libpng"),
    Component(
        "cairo",
        "cairo",
        "MPL-1.1 (elected from LGPL-2.1-only OR MPL-1.1)",
        "2D vector drawing for tier 4",
    ),
    Component("pixman", "pixman", "MIT AND BSD-2-Clause", "rasterization for cairo"),
    Component(
        "freetype",
        "FreeType",
        "FTL (elected from FTL OR GPL-2.0-or-later)",
        "font rendering for cairo",
    ),
    Component("expat", "Expat", "MIT", "dependency of cairo"),
    Component("pthreads", "PThreads4W", "Apache-2.0", "threads for cairo and pixman on Windows"),
    Component("dirent", "dirent (Windows)", "MIT", "dependency of cairo on Windows"),
)

FONT = REPO / "resources" / "fonts" / "OFL.txt"

HEADER = """# Third-party notices

The cadpreview library binaries (cadpreview.dll, libcadpreview.so, and the CadPreview NuGet
package) include the components below, linked statically. Test-only and build-only tools are
not distributed and are listed in notes/licenses.md. Generated by
tools/third_party_notices.py; do not edit by hand.

cairo is used under the Mozilla Public License 1.1. Its unmodified source is available from
https://www.cairographics.org/releases/ (version 1.18.6); cadpreview changes only cairo's build
script (see ports/README.md), not its source files.

Builds configured with CADPREVIEW_WITH_DWG=ON also link LibreDWG and jsmn. Those builds are
licensed GPL-3.0-or-later as a whole; their notices are installed alongside them.
"""


def section(title: str, license_id: str, purpose: str, text: str) -> str:
    heading = f"\n## {title}\n\nLicense: {license_id}. Used for {purpose}.\n\n"
    return f"{heading}```text\n{text.strip()}\n```\n"


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        sys.stderr.write(__doc__ or "")
        return 2
    share = Path(argv[1]) / "share"
    parts = [HEADER]
    for component in SHIPPED:
        text = (share / component.port / "copyright").read_text(encoding="utf-8", errors="replace")
        parts.append(section(component.name, component.license, component.purpose, text))
    parts.append(
        section(
            "Noto Sans (Latin subset, embedded)",
            "OFL-1.1",
            "text in tier-4 previews",
            FONT.read_text(encoding="utf-8"),
        )
    )
    (REPO / "THIRD_PARTY_NOTICES.md").write_text("".join(parts), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
